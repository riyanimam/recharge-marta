const i18nState = reactive({
  lang: "en" as SupportedLang,
});

export function useAppI18n() {
  function setLanguage(lang: SupportedLang) {
    i18nState.lang = lang;
  }

  function t(key: string): string {
    return TRANSLATIONS[i18nState.lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  }

  return {
    currentLang: computed(() => i18nState.lang),
    languageLabels: LANGUAGE_LABELS,
    languageKeys: Object.keys(LANGUAGE_LABELS) as SupportedLang[],
    setLanguage,
    t,
  };
}
